// Helper for extracting YouTube ID
function getYTId(url) {
  if (!url) return "";
  const match = url.match(/(?:youtube\.com\/(?:watch\?v=|embed\/|live\/)|youtu\.be\/)([^&\n?#]+)/);
  return match ? match[1] : "";
}

