async function seedDatabase() {
  try {
    console.log("Connecting to MongoDB for seeding...");
    await mongoose.connect(MONGODB_URI);
    console.log("Connected successfully.");

    // Create Admin User only if environment variables are provided
    if (process.env.ADMIN_EMAIL && process.env.ADMIN_PASSWORD) {
      const adminEmail = process.env.ADMIN_EMAIL.toLowerCase().trim();
      const existingAdmin = await User.findOne({ email: adminEmail });
      if (!existingAdmin) {
        const salt = await bcrypt.genSalt(10);
        const hashedPassword = await bcrypt.hash(process.env.ADMIN_PASSWORD, salt);
        await User.create({
          name: "System Administrator",
          email: adminEmail,
          password: hashedPassword,
          role: "admin",
          stream: "Science",
          class: "12",
        });
        console.log(`Created Initial Admin Account: ${adminEmail}`);
      }
    }

    // Seed/Upsert Videos
    console.log(`Seeding ${INITIAL_VIDEOS.length} syllabus video entries...`);
    for (const v of INITIAL_VIDEOS) {
      const ytId = getYTId(v.videoUrl);
      await Video.findOneAndUpdate(
        { chapterId: v.chapterId },
        {
          ...v,
          youtubeId: ytId,
          isAvailable: Boolean(ytId),
        },
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    }

    console.log("Syllabus videos seeded successfully!");
    process.exit(0);
  } catch (err) {
    console.error("Seeding error:", err);
    process.exit(1);
  }
}

seedDatabase();
